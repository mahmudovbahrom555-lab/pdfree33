#!/usr/bin/env python3
"""Generates js/cmykRgbLut.js — the CMYK → RGB table Compress's "Screen & email" mode uses.

16 nodes per channel (exact step 17: 0, 17, … 255), each converted by MuPDF with colour
management on (its built-in default CMYK profile; pure cyan → 0,174,239), the way an
ICC-managed reader shows DeviceCMYK. Read with quadrilinear interpolation (js/cmykD.js).
Grid size chosen on random synthetic colours, never on documents (wip-bench SCREEN-PREREG.md):
ΔE76 vs direct conversion mean 0.28, p99 1.18 — one CMYK input step alone is p99 0.98.

python3 scripts/gen_cmyk_rgb_lut.py   (needs PyMuPDF; output is committed)
"""
import base64, os
import fitz, numpy as np

G, STEP = 16, 17
ax = np.arange(G) * STEP
grid = np.stack(np.meshgrid(ax, ax, ax, ax, indexing='ij'), -1).reshape(-1, 4).astype(np.uint8)
fitz.TOOLS.set_icc(True)
src = fitz.Pixmap(fitz.csCMYK, len(grid), 1, grid.tobytes(), 0)
lut = fitz.Pixmap(fitz.csRGB, src).samples
assert len(lut) == G ** 4 * 3 and tuple(lut[(15 * G ** 3) * 3:(15 * G ** 3) * 3 + 3]) == (0, 174, 239)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'cmykRgbLut.js')
with open(out, 'w') as f:
    f.write('// SPDX-License-Identifier: AGPL-3.0-only\n')
    f.write('// Generated by scripts/gen_cmyk_rgb_lut.py — do not edit. CMYK → RGB, 16 nodes per\n')
    f.write('// channel (C, M, Y, K order, step 17), 3 bytes each: MuPDF\'s ICC-managed conversion.\n')
    f.write("(() => { const s = atob('" + base64.b64encode(lut).decode() + "');\n")
    f.write('  const t = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) t[i] = s.charCodeAt(i);\n')
    f.write('  self.cmykRgbLut = t; })();\n')
print('wrote', out, len(lut), 'bytes')

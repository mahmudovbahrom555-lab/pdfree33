// ── Markdown structural signal extraction (no ground truth needed) ──────
function countHeadings(md)  { return (md.match(/^#{1,6}\s+\S/gm) || []).length; }
function countLists(md)     { return (md.match(/^(?:-\s|\d+\.\s)/gm) || []).length; }
function countTables(md)    { return (md.match(/^\|.+\|\n\|[-:| ]+\|/gm) || []).length; }
function countImages(md)    { return (md.match(/!\[[^\]]*\]\([^)]+\.png\)/g) || []).length; }
function countFormulas(md)  { return (md.match(/^\$\$\n[\s\S]*?\n\$\$/gm) || []).length; }

// Cheap, real structural-validity checks — not exhaustive Markdown
// linting, just the failure modes this pipeline could plausibly produce:
// unbalanced bold markers, a table row with a different cell count than
// its header, an unterminated formula block.
function validityIssues(md) {
  const issues = [];
  const boldMarkers = (md.match(/\*\*/g) || []).length;
  if (boldMarkers % 2 !== 0) issues.push('unbalanced ** bold markers');
  const dollarBlocks = (md.match(/^\$\$$/gm) || []).length;
  if (dollarBlocks % 2 !== 0) issues.push('unbalanced $$ display-math delimiters');
  return issues;
}

async function extractDocMd(filePath) {
  if (filePath.endsWith('.zip')) {
    const buf = fs.readFileSync(filePath);
    const zip = await JSZip.loadAsync(buf);
    const entry = zip.file('document.md');
    return entry ? entry.async('string') : '';
  }
  return fs.readFileSync(filePath, 'utf8');
}

async function runOne(entry) {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const t0 = Date.now();
  let result = { name: entry.name, category: entry.category, note: entry.note, error: null };
  try {
    await page.goto(`${BASE}/pdf-to-markdown/`, { waitUntil: 'networkidle', timeout: 30000 });
    await page.setInputFiles('#fileInput', entry.file);
    await page.waitForFunction(() => {
      const el = document.getElementById('pdf2mdOptions');
      return el && el.style.display !== 'none' && !el.textContent.toLowerCase().includes('analysing');
    }, { timeout: 30000 });

    const dl = page.waitForEvent('download', { timeout: 90000 });
    await page.click('#mergeBtn');
    const download = await dl;
    const savePath = path.join('/tmp', `bench_${entry.name}${path.extname(download.suggestedFilename())}`);
    await download.saveAs(savePath);
    const elapsedMs = Date.now() - t0;

    await page.waitForTimeout(600); // let #atlasCheck finish rendering
    const atlasVisible = await page.locator('#atlasCheck').isVisible().catch(() => false);
    const atlasText = atlasVisible ? await page.locator('#atlasCheck').innerText() : null;
    const atlasEriMatch = atlasText ? atlasText.match(/(\d+)%/) : null;

    const md = await extractDocMd(savePath);
    fs.unlinkSync(savePath);

    result = {
      ...result,
      elapsedMs,
      outputBytes: Buffer.byteLength(md, 'utf8'),
      atlasEri: atlasEriMatch ? Number(atlasEriMatch[1]) : null,
      atlasVerdict: atlasText ? atlasText.split('\n')[1] : null,
      structural: {
        headings: countHeadings(md), lists: countLists(md),
        tables: countTables(md), images: countImages(md), formulas: countFormulas(md),
      },
      validityIssues: validityIssues(md),
      isEmpty: md.trim().length === 0,
    };

    if (entry.expect) {
      const exp = entry.expect;
      if (exp.scan) {
        // See the corpus entry's own comment for why this accepts either
        // real outcome (OCR hint OR a real image reference) as "graceful",
        // and separately reports whether the hint specifically fired.
        const ocrHintShown = /no.*extractable text|try ocr/i.test(md);
        const gotRealImage = result.structural.images > 0;
        result.groundTruth = {
          pass: ocrHintShown || gotRealImage,
          ocrHintShown,
          gotRealImage,
          expected: 'graceful handling (OCR hint or a real image reference) — not a crash or garbled/empty output',
        };
      } else {
        const checks = {
          headings: result.structural.headings === exp.headings,
          tables:   result.structural.tables === exp.tables,
          images:   result.structural.images === exp.images,
          formulas: result.structural.formulas === exp.formulas,
        };
        const passCount = Object.values(checks).filter(Boolean).length;
        result.groundTruth = { pass: passCount === 4, checks, expected: exp, actual: result.structural, accuracyPct: Math.round(passCount / 4 * 100) };
      }
    }
  } catch (err) {
    result.error = err.message;
  } finally {
    await browser.close();
  }
  return result;
}

async function main() {
  console.log(`Benchmarking pdf2md against ${BASE} — ${CORPUS.length} documents\n`);
  const results = [];
  for (const entry of CORPUS) {
    if (!fs.existsSync(entry.file)) {
      console.log(`  ⚠ SKIP ${entry.name} — file not found at ${entry.file}`);
      continue;
    }
    process.stdout.write(`  running ${entry.name} (${entry.category})... `);
    const r = await runOne(entry);
    results.push(r);
    console.log(r.error ? `ERROR: ${r.error}` : `${r.elapsedMs}ms, atlas=${r.atlasEri ?? 'n/a'}%`);
  }

  console.log(`\n${'='.repeat(78)}`);
  console.log('REAL DOCUMENTS (no hand-verified ground truth — structural signals only)');
  console.log('='.repeat(78));
  for (const r of results.filter(r => r.category === 'real')) {
    if (r.error) { console.log(`${r.name}: ERROR — ${r.error}`); continue; }
    console.log(`\n${r.name}  (${r.elapsedMs}ms, ${r.outputBytes}B)`);
    console.log(`  Atlas ERI: ${r.atlasEri ?? 'n/a'}%  ${r.atlasVerdict ?? ''}`);
    console.log(`  headings=${r.structural.headings} lists=${r.structural.lists} tables=${r.structural.tables} images=${r.structural.images} formulas=${r.structural.formulas}`);
    if (r.validityIssues.length) console.log(`  ⚠ validity issues: ${r.validityIssues.join(', ')}`);
  }

  console.log(`\n${'='.repeat(78)}`);
  console.log('SYNTHETIC DOCUMENTS (exact ground truth — this project built them)');
  console.log('='.repeat(78));
  let gtTotal = 0, gtSum = 0;
  for (const r of results.filter(r => r.category === 'synthetic')) {
    if (r.error) { console.log(`${r.name}: ERROR — ${r.error}`); continue; }
    console.log(`\n${r.name}  (${r.note})`);
    if (r.groundTruth) {
      if ('accuracyPct' in r.groundTruth) {
        gtTotal++; gtSum += r.groundTruth.accuracyPct;
        console.log(`  Ground-truth match: ${r.groundTruth.accuracyPct}% ${r.groundTruth.pass ? '✓' : '✗'}`);
        console.log(`  expected: ${JSON.stringify(r.groundTruth.expected)}`);
        console.log(`  actual:   ${JSON.stringify(r.groundTruth.actual)}`);
      } else {
        gtTotal++; gtSum += r.groundTruth.pass ? 100 : 0;
        console.log(`  Ground-truth: ${r.groundTruth.pass ? 'PASS ✓' : 'FAIL ✗'} (${r.groundTruth.expected})`);
        if ('ocrHintShown' in r.groundTruth) {
          console.log(`    OCR hint shown: ${r.groundTruth.ocrHintShown}  |  real image reference: ${r.groundTruth.gotRealImage}`);
        }
      }
    }
    if (r.atlasEri !== null) console.log(`  Atlas ERI: ${r.atlasEri}%`);
    if (r.validityIssues.length) console.log(`  ⚠ validity issues: ${r.validityIssues.join(', ')}`);
  }

  console.log(`\n${'='.repeat(78)}`);
  console.log(`SUMMARY: ${results.filter(r=>!r.error).length}/${results.length} processed without error`);
  if (gtTotal) console.log(`Synthetic-corpus ground-truth accuracy: ${(gtSum / gtTotal).toFixed(1)}% average across ${gtTotal} docs`);
  const realWithAtlas = results.filter(r => r.category === 'real' && r.atlasEri !== null);
  if (realWithAtlas.length) {
    const avgAtlas = realWithAtlas.reduce((s, r) => s + r.atlasEri, 0) / realWithAtlas.length;
    console.log(`Real-document average Atlas ERI: ${avgAtlas.toFixed(1)}% (structural signal, not an accuracy claim)`);
  }

  if (OUT_JSON) {
    fs.writeFileSync(OUT_JSON, JSON.stringify(results, null, 2));
    console.log(`\nFull results written to ${OUT_JSON}`);
  }
}

main();

// ============================================================
//  pdf2md_benchmark.mjs — real-document benchmark harness for pdf2md.
//
//  Drives the actual browser tool via Playwright against a real running
//  `dist/` (or production) instance, exactly the way a user would — not a
//  Node-only call into _p2mdExtractText, since that would skip the real
//  canvas-based image/formula-crop path and the real Atlas ERI badge
//  rendering this is trying to measure.
//
//  Two honesty tiers, reported separately, never conflated:
//    - GROUND-TRUTH corpus (corpus/synthetic/*): documents this project
//      itself constructed (scripts/gen_benchmark_corpus.py), so the
//      expected structure (table count, formula count, heading count...)
//      is exactly known. Real accuracy percentages against that known
//      truth.
//    - NO-GROUND-TRUTH corpus (real arXiv papers, tests/fixtures/columns/):
//      no hand-verified expected output exists for these. Reports Atlas
//      ERI + structural signals only — never presented as an "accuracy %"
//      claim, because there is no ground truth to measure accuracy against.
//
//  Usage:
//    node scripts/pdf2md_benchmark.mjs --base http://localhost:PORT [--out report.json]
//
//  Requires a running static server over a built dist/ (or production) —
//  this script does not start one itself, matching every other real
//  Playwright verification this project's own sessions have used.
// ============================================================

import { chromium } from 'playwright';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import JSZip from 'jszip';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const args = process.argv.slice(2);
const getArg = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i !== -1 && args[i + 1] ? args[i + 1] : def;
};
const BASE = getArg('base', 'http://localhost:8080');
const OUT_JSON = getArg('out', null);
// Generated by scripts/gen_benchmark_corpus.py — gitignored, run that
// script first if this directory doesn't exist yet.
const CORPUS_DIR = getArg('corpus', path.join(ROOT, 'benchmark_corpus'));

// ── Corpus definition ────────────────────────────────────────────────────

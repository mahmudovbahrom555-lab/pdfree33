// Builds js/digitTemplates.js — the reference digits js/digitGlyphs.js
// matches a PDF's digit glyphs against (class C4, tests/corpus/ERROR_CLASSES.md).
//
// Each font's Latin, Arabic-Indic and Persian digits are drawn with the same
// code that judges the PDF's glyphs (glyphPolygons → rasterize), so the
// references and the glyphs under test are made alike. Fonts: open-licensed
// (SIL OFL / Apache) from github.com/google/fonts — Amiri, Lateef,
// Scheherazade New, Harmattan, Noto Naskh/Sans Arabic, Vazirmatn, Tajawal,
// El Messiri, Reem Kufi, Noto Sans/Serif, Tinos, Arimo, Cousine. Only the
// 24×24 digit pictures are kept, not the fonts.
//
// Run: node scripts/gen_digit_templates.mjs <font.ttf>... > js/digitTemplates.js
import fs from 'fs';
import path from 'path';
import { parseFont, fontTemplates, SIZE } from '../js/digitGlyphs.js';

const rows = [];
const used = [];
for (const file of process.argv.slice(2)) {
  const font = parseFont(new Uint8Array(fs.readFileSync(file)));
  if (!font) continue;
  const t = fontTemplates(font);
  if (!t.length) continue;
  used.push(`${path.basename(file, '.ttf')} (${t.length})`);
  for (const { value, relH, img } of t) {
    // value, relative height (0..255), then the picture at 4 bits a pixel
    const b = new Uint8Array(2 + SIZE * SIZE / 2);
    b[0] = value;
    b[1] = Math.round(relH * 255);
    for (let i = 0; i < img.length; i += 2) b[2 + i / 2] = (Math.round(img[i] * 15) << 4) | Math.round(img[i + 1] * 15);
    rows.push(Buffer.from(b).toString('base64'));
  }
}
process.stdout.write(`// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/gen_digit_templates.mjs — do not edit. Reference
// digits for js/digitGlyphs.js, drawn from: ${used.join(', ')}.
import { SIZE } from './digitGlyphs.js';

const ROWS = ${JSON.stringify(rows).replace(/","/g, '",\n  "')};

let decoded = null;
export function digitTemplates() {
  decoded ??= ROWS.map(r => {
    const b = Uint8Array.from(atob(r), c => c.charCodeAt(0));
    const img = new Float32Array(SIZE * SIZE);
    for (let i = 0; i < img.length; i += 2) { img[i] = (b[2 + i / 2] >> 4) / 15; img[i + 1] = (b[2 + i / 2] & 15) / 15; }
    return { value: b[0], relH: b[1] / 255, img, norm2: img.reduce((s, x) => s + x * x, 0) };
  });
  return decoded;
}
`);

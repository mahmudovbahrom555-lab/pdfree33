#!/usr/bin/env python3
"""Writes js/cjkRadicals.js: CJK Radicals Supplement characters (U+2E80–U+2EFF) → the ordinary ideograph
that the self-hosted Noto Sans SC draws with the same glyph. Unicode's own normalization maps the Kangxi
radicals (U+2F00–U+2FDF, NFKC) but not these; a PDF can store 页 as ⻚ (Chrome-printed Chinese, 2026-11-13),
and Quick Edit's Find must still match the 页 a person types.
  python3 scripts/gen_cjk_radicals.py"""
import json, os
from fontTools.ttLib import TTFont
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cmap = TTFont(os.path.join(ROOT, 'js/vendor/noto/notosanssc-v40.ttf')).getBestCmap()
by_glyph = {}
for cp, glyph in sorted(cmap.items()):
    if 0x3400 <= cp <= 0x9FFF or 0x20000 <= cp <= 0x2FFFF:
        by_glyph.setdefault(glyph, cp)
pairs = ''.join(chr(cp) + chr(by_glyph[cmap[cp]]) for cp in sorted(cmap) if 0x2E80 <= cp <= 0x2EFF and cmap[cp] in by_glyph)
with open(os.path.join(ROOT, 'js/cjkRadicals.js'), 'w', encoding='utf-8') as out:
    out.write('// SPDX-License-Identifier: AGPL-3.0-only\n'
              '// Generated by scripts/gen_cjk_radicals.py from js/vendor/noto/notosanssc-v40.ttf — do not edit.\n'
              '// Pairs: a CJK Radicals Supplement character, then the ideograph drawn with the same glyph.\n'
              f'const PAIRS = {json.dumps(pairs, ensure_ascii=False)};\n'
              'const CHARS = Array.from(PAIRS);   // by code point: some ideographs are outside the BMP\n'
              'export const RADICAL_IDEOGRAPH = new Map(Array.from({ length: CHARS.length / 2 }, (_, i) => [CHARS[2 * i], CHARS[2 * i + 1]]));\n')
print(len(pairs) // 2, 'pairs')
